type DemoVariantInput = {
  id: string;
  name: string;
  priceGhs: number;
  inStock?: boolean;
  sku?: string;
  packSize?: string;
  image?: string;
};

type DemoProductInput = Omit<
  CatalogueProduct,
  "variants" | "priceGhs" | "priceLabel" | "inStock"
> & {
  variants: DemoVariantInput[];
};

function buildVariant(input: DemoVariantInput): CatalogueProductVariant {
  return {
    id: input.id,
    name: input.name,
    priceGhs: input.priceGhs,
    priceLabel: formatGhs(input.priceGhs),
    inStock: input.inStock ?? true,
    sku: input.sku,
    packSize: input.packSize,
    image: input.image,
  };
}

/** Derive product-level price/stock from variants for filters and cards. */
function buildProduct(input: DemoProductInput): CatalogueProduct {
  const variants = input.variants.map(buildVariant);
  if (variants.length === 0) {
    throw new Error(`Demo product ${input.id} must have at least one variant`);
  }

  const starting = Math.min(...variants.map((variant) => variant.priceGhs));
  const anyInStock = variants.some((variant) => variant.inStock);

  return {
    ...input,
    variants,
    priceGhs: starting,
    priceLabel: formatGhs(starting),
    inStock: anyInStock,
  };
}

